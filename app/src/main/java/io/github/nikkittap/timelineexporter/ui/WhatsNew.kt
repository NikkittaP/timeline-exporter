/**
 * One release's in-app notes: [notes] is a string resource holding one item
 * per line. The list itself, [WHATS_NEW_NOTES], is generated by
 * tools/whats_new.py from the store's tagged changelog, so the popup says the
 * same as the Play listing, in the same 18 languages.
 */
data class WhatsNewEntry(val version: String, @StringRes val notes: Int)

/**
 * Which notes to show, kept free of Android so the tests can call it.
 *
 * The first launch on a new version shows what changed since the last version
 * whose notes this user saw - every release in between, if they skipped some,
 * each under its own header. A fresh install has nothing "new" and only
 * records its version. Someone updating from a build older than this feature
 * has no version recorded yet; they get the current release's notes only.
 */
object WhatsNew {

    /** "1.10.0" vs "1.9.2" by numeric parts, missing parts as 0. */
    fun compare(a: String, b: String): Int {
        val pa = a.split('.').map { it.toIntOrNull() ?: 0 }
        val pb = b.split('.').map { it.toIntOrNull() ?: 0 }
        for (i in 0 until maxOf(pa.size, pb.size)) {
            val x = pa.getOrElse(i) { 0 }
            val y = pb.getOrElse(i) { 0 }
            if (x != y) return x.compareTo(y)
        }
        return 0
    }

    /**
     * The entries to show now, newest first: newer than [seen] and not newer
     * than [current]. [seen] null means no version was recorded: an [updated]
     * install gets [current]'s notes, a fresh one gets none.
     */
    fun pending(
        entries: List<WhatsNewEntry>,
        seen: String?,
        current: String,
        updated: Boolean,
    ): List<WhatsNewEntry> {
        if (seen == null && !updated) return emptyList()
        return entries
            .filter { compare(it.version, current) <= 0 }
            .filter { if (seen == null) compare(it.version, current) == 0 else compare(it.version, seen) > 0 }
            .sortedWith { a, b -> compare(b.version, a.version) }
    }

    /** Every release up to [current], newest first: the footer's full list. */
    fun history(entries: List<WhatsNewEntry>, current: String): List<WhatsNewEntry> =
        entries
            .filter { compare(it.version, current) <= 0 }
            .sortedWith { a, b -> compare(b.version, a.version) }
}

/**
 * The popup's state: [pending] is what to show after an update, empty when
 * nothing. The version counts as seen only once the popup is closed, so a
 * popup the process died under comes back on the next launch.
 */
class WhatsNewState internal constructor(
    private val prefs: SharedPreferences,
    private val current: String,
    updated: Boolean,
) {
    var pending: List<WhatsNewEntry> by mutableStateOf(
        WhatsNew.pending(WHATS_NEW_NOTES, prefs.getString(KEY_SEEN, null), current, updated),
    )
        private set

    init {
        // Nothing to show (fresh install, or no notes for this build): record
        // the version now, so the next update compares against this one.
        if (pending.isEmpty() && prefs.getString(KEY_SEEN, null) != current) markSeen()
    }

    fun dismiss() {
        pending = emptyList()
        markSeen()
    }

    private fun markSeen() {
        prefs.edit().putString(KEY_SEEN, current).apply()
    }

    companion object {
        const val PREFS = "whats_new"
        const val KEY_SEEN = "seen_version"
    }
}

@Composable
fun rememberWhatsNew(): WhatsNewState {
    val context = LocalContext.current.applicationContext
    return remember {
        WhatsNewState(
            prefs = context.getSharedPreferences(WhatsNewState.PREFS, Context.MODE_PRIVATE),
            current = BuildConfig.VERSION_NAME,
            updated = wasUpdated(context),
        )
    }
}

/** Installed over an earlier version rather than fresh: the two times differ. */
private fun wasUpdated(context: Context): Boolean = try {
    @Suppress("DEPRECATION")
    val info = context.packageManager.getPackageInfo(context.packageName, 0)
    info.firstInstallTime != info.lastUpdateTime
} catch (_: PackageManager.NameNotFoundException) {
    false
}

/**
 * The notes of [entries], newest first, each release under its version. Used
 * both for the popup after an update and for the full list behind the version
 * line at the bottom of the screen; only the [title] differs.
 */
@Composable
fun WhatsNewDialog(
    title: String,
    entries: List<WhatsNewEntry>,
    onDismiss: () -> Unit,
) {
    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text(title) },
        text = {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(6.dp),
            ) {
                entries.forEachIndexed { index, entry ->
                    Text(
                        stringResource(R.string.app_version, entry.version),
                        style = MaterialTheme.typography.titleSmall,
                        modifier = Modifier.padding(top = if (index == 0) 0.dp else 10.dp),
                    )
                    stringResource(entry.notes).lines().filter { it.isNotBlank() }.forEach { item ->
                        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                            Text("•", style = MaterialTheme.typography.bodyMedium)
                            Text(item, style = MaterialTheme.typography.bodyMedium)
                        }
                    }
                }
            }
        },
        confirmButton = {
            TextButton(onClick = onDismiss) { Text(stringResource(R.string.whats_new_close)) }
        },
    )
}
