#!/usr/bin/env python3
"""In-app "What's new" notes from the store's tagged changelog files.

    python tools/whats_new.py ../Whats_New_v1.9.3_tagged.txt [more files...]

Each argument is one `Whats_New_v<versionName>_tagged.txt` (the 18-locale block
pasted into Play Console, see RELEASE_NOTES.md). Its version is taken from the
file name. The notes are MERGED into what the app already has, so running it
with just the new release's file is enough; giving a version again replaces it.

Writes, for every locale:
    app/src/main/res/values[-xx]/whats_new.xml   whats_new_<1_9_3> strings, one
                                                 line per item, newest first
and the version list the app reads:
    app/src/main/java/.../ui/WhatsNewNotes.kt

Those generated files are the source of truth for the app; the tagged files
outside the repo may be deleted afterwards.
"""

import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app" / "src" / "main" / "res"
KOTLIN = (ROOT / "app" / "src" / "main" / "java" / "io" / "github" / "nikkittap"
          / "timelineexporter" / "ui" / "WhatsNewNotes.kt")

# Play Console tag -> resource folder suffix.
LOCALES = {
    "en-US": "", "ru-RU": "-ru", "uk": "-uk", "de-DE": "-de", "fr-FR": "-fr",
    "es-ES": "-es", "it-IT": "-it", "pt-BR": "-pt-rBR", "nl-NL": "-nl",
    "sv-SE": "-sv", "pl-PL": "-pl", "tr-TR": "-tr", "ja-JP": "-ja",
    "ko-KR": "-ko", "zh-CN": "-zh-rCN", "zh-TW": "-zh-rTW", "hi-IN": "-hi",
    "ar": "-ar",
}
NAME = re.compile(r"Whats_New_v(\d+(?:\.\d+)*)_tagged\.txt$")
BLOCK = re.compile(r"^<([A-Za-z-]+)>\s*\n(.*?)\n</\1>", re.S | re.M)


def vkey(v: str) -> tuple[int, ...]:
    return tuple(int(x) for x in v.split("."))


def res_name(v: str) -> str:
    return "whats_new_" + v.replace(".", "_")


def parse_tagged(path: pathlib.Path) -> tuple[str, dict[str, list[str]]]:
    m = NAME.search(path.name)
    if not m:
        sys.exit(f"{path.name}: expected Whats_New_v<version>_tagged.txt")
    text = path.read_text(encoding="utf-8")
    out = {}
    for tag, body in BLOCK.findall(text):
        if tag not in LOCALES:
            sys.exit(f"{path.name}: unknown locale <{tag}>")
        items = [re.sub(r"^[•\-*]\s*", "", ln).strip() for ln in body.splitlines()]
        out[tag] = [i for i in items if i]
    missing = sorted(set(LOCALES) - set(out))
    if missing:
        sys.exit(f"{path.name}: missing locales {', '.join(missing)}")
    return m.group(1), out


def android_escape(s: str) -> str:
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"')
    if s.startswith(("@", "?")):
        s = "\\" + s
    return s


def android_unescape(s: str) -> str:
    out, i = [], 0
    while i < len(s):
        c = s[i]
        if c == "\\" and i + 1 < len(s):
            n = s[i + 1]
            out.append("\n" if n == "n" else n)
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def read_existing(path: pathlib.Path) -> dict[str, list[str]]:
    """version -> items from a whats_new.xml this script wrote earlier."""
    if not path.exists():
        return {}
    out = {}
    for el in ET.parse(path).getroot().iter("string"):
        v = el.get("name", "").removeprefix("whats_new_").replace("_", ".")
        out[v] = android_unescape(el.text or "").split("\n")
    return out


def write_xml(path: pathlib.Path, notes: dict[str, list[str]]) -> None:
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- Generated by tools/whats_new.py from the store's tagged changelogs.",
        "     One string per release, one line per item. Edit, then keep the",
        "     other locales in step; or rerun the tool. -->",
        "<resources>",
    ]
    for v in sorted(notes, key=vkey, reverse=True):
        body = "\\n".join(android_escape(i) for i in notes[v])
        lines.append(f'    <string name="{res_name(v)}">{body}</string>')
    lines.append("</resources>")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_kotlin(versions: list[str]) -> None:
    entries = "\n".join(
        f'    WhatsNewEntry("{v}", R.string.{res_name(v)}),'
        for v in sorted(versions, key=vkey, reverse=True)
    )
    KOTLIN.write_text(
        "// Generated by tools/whats_new.py - do not edit by hand.\n"
        "package io.github.nikkittap.timelineexporter.ui\n\n"
        "import io.github.nikkittap.timelineexporter.R\n\n"
        "/** Every release with in-app notes, newest first. */\n"
        "val WHATS_NEW_NOTES: List<WhatsNewEntry> = listOf(\n"
        f"{entries}\n"
        ")\n",
        encoding="utf-8",
    )


def main(args: list[str]) -> None:
    if not args:
        sys.exit(__doc__)
    incoming = [parse_tagged(pathlib.Path(a)) for a in args]
    versions: set[str] = set()
    for tag, suffix in LOCALES.items():
        path = RES / f"values{suffix}" / "whats_new.xml"
        notes = read_existing(path)
        for v, per_locale in incoming:
            notes[v] = per_locale[tag]
        write_xml(path, notes)
        if suffix == "":
            versions = set(notes)
    write_kotlin(sorted(versions))
    print(f"{len(versions)} versions: {', '.join(sorted(versions, key=vkey, reverse=True))}")


if __name__ == "__main__":
    main(sys.argv[1:])
